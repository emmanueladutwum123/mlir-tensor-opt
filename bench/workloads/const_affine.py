"""Generate const_affine.mlir (6 MB of constant data; not worth committing).

Target: constant folding. y = x * (w * s + b) where w, s, b are non-splat
compile-time constants (a weight, a per-element scale and a bias baked into
the program). Folding evaluates w * s + b once at compile time.

The constants must be non-splat (a splat already becomes a scalar during
lowering, so there would be nothing to save) and at most 2^18 elements (the
fold budget), hence 512x512. A seeded RNG keeps the file reproducible.
"""
import random
import struct
import sys

N = 512
random.seed(7)


def payload(count: int) -> str:
    raw = b"".join(struct.pack("<f", random.uniform(-2.0, 2.0)) for _ in range(count))
    return "0x" + raw.hex().upper()


t = f"tensor<{N}x{N}xf32>"
sys.stdout.write(f"""// Generated by bench/workloads/const_affine.py. Do not edit.
func.func @kernel(%x: {t}) -> {t} attributes {{llvm.emit_c_interface}} {{
  %w = topt.constant dense<"{payload(N * N)}"> : {t}
  %s = topt.constant dense<"{payload(N * N)}"> : {t}
  %b = topt.constant dense<"{payload(N * N)}"> : {t}
  %ws = topt.mul %w, %s : {t}
  %k = topt.add %ws, %b : {t}
  %y = topt.mul %x, %k : {t}
  return %y : {t}
}}
""")
